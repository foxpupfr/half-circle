from enum import Enum


class tokentype(Enum):

# basic operators
    PLUS = "+"
    MINUS = "-"
    MULPLICATION = "*"
    DIVISION = "/"
    EQUAL_TO = "="
    GREATER_THAN = ">"
    LESS_THAN = "<"
    GREATER_THAN_OR_EQUAL_TO = ">="
    LESS_THAN_OR_EQUAL_TO = "<="

# whitespace
    WHITESPACE = " "

# variable
    VARIABLE = Enum

# numbers
    NUMBER = Enum
